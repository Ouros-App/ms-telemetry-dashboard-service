def _corporate_cost_by_region(
    scoped_farm_ids: set[Any],
    all_farms: list[dict[str, Any]],
    target_year: int | None,
    target_month: int | None,
    records: Any,
) -> list[dict[str, Any]]:
    effective_curr_year = target_year or datetime.now(UTC).year
    effective_prev_year = effective_curr_year - 1
    farm_by_id = {f["farm_id"]: f for f in all_farms if f.get("farm_id") is not None}

    curr_lots_costs: dict[str, list[Decimal]] = defaultdict(list)
    prev_lots_costs: dict[str, list[Decimal]] = defaultdict(list)

    for lot in records(ROWS, "fact_lot"):
        fid = lot.get("farm_id")
        if fid not in scoped_farm_ids:
            continue
        d = _day(lot.get("delivery_date") or lot.get("date") or datetime.now(UTC))
        if target_month is not None and d.month != target_month:
            continue
        cost = _number(lot.get("cost"))
        farm_doc = farm_by_id.get(fid)
        region = _resolve_region(farm_doc, lot)
        if d.year == effective_curr_year:
            curr_lots_costs[region].append(cost)
        elif d.year == effective_prev_year:
            prev_lots_costs[region].append(cost)

    reg_stats = {}
    for reg in REGIONS:
        curr_stats = _calc_box_stats(curr_lots_costs[reg])
        prev_stats = _calc_box_stats(prev_lots_costs[reg])
        reg_stats[reg] = (curr_stats, prev_stats)

    curr_totals = [
        float(stats[0]["total_cost"])
        for stats in reg_stats.values()
        if stats[0]["total_cost"] > 0
    ]
    faixas = _calcular_faixas_custo_dinamicas(
        curr_totals, num_baldes=len(FIGMA_GRADIENT)
    )

    result: list[dict[str, Any]] = []
    for reg in REGIONS:
        curr_stats, prev_stats = reg_stats[reg]
        curr_total = curr_stats["total_cost"]
        prev_total = prev_stats["total_cost"]
        color, bucket_name = _resolve_bucket_and_color(curr_total, faixas=faixas)

        result.append(
            {
                "region": reg,
                "previous_year_cost": prev_total,
                "current_year_cost": curr_total,
                "cost": curr_total,
                "color": color,
                "bucket": bucket_name,
                "previous_year": prev_stats,
                "current_year": curr_stats,
            }
        )
    return result


def _corporate_monthly_cost(
    scoped_farm_ids: set[Any],
    target_year: int | None,
    records: Any,
) -> list[dict[str, Any]]:
    effective_curr_year = target_year or datetime.now(UTC).year
    effective_prev_year = effective_curr_year - 1
    curr_by_month: dict[int, Decimal] = defaultdict(Decimal)
    prev_by_month: dict[int, Decimal] = defaultdict(Decimal)

    for lot in records(ROWS, "fact_lot"):
        if lot.get("farm_id") not in scoped_farm_ids:
            continue
        d = _day(lot.get("delivery_date") or lot.get("date") or datetime.now(UTC))
        cost = _number(lot.get("cost"))
        if d.year == effective_curr_year:
            curr_by_month[d.month] += cost
        elif d.year == effective_prev_year:
            prev_by_month[d.month] += cost

    return [
        {
            "month": m,
            "month_label": MONTH_LABELS[m],
            "previous_year_cost": _rounded(prev_by_month[m], 2),
            "current_year_cost": _rounded(curr_by_month[m], 2),
            "cost": _rounded(curr_by_month[m], 2),
        }
        for m in range(1, 13)
    ]


def _exec_corporate_charts(
    operation: str,
    scoped_farm_ids: set[Any],
    all_farms: list[dict[str, Any]],
    target_year: int | None,
    target_month: int | None,
    cutoff: datetime | None,
    records: Any,
) -> list[dict[str, Any]]:
    if operation in {"trend_kwh_aves", "trend_liters_aves"}:
        return _corporate_trend(operation, scoped_farm_ids, cutoff, records)
    if operation == "cost_distribution_buckets":
        return _corporate_cost_distribution_buckets(
            scoped_farm_ids, all_farms, target_year, target_month, records
        )
    if operation == "cost_by_lot_size_cohort":
        return _corporate_cost_by_lot_size_cohort(
            scoped_farm_ids, target_year, target_month, records
        )
    if operation == "cost_by_region":
        return _corporate_cost_by_region(
            scoped_farm_ids, all_farms, target_year, target_month, records
        )
    if operation == "monthly_cost":
        return _corporate_monthly_cost(scoped_farm_ids, target_year, records)
    raise AnalyticsQueryError(f"Unknown corporate operation: {operation}")


def _corporate_farms_table(
    scoped_farms: list[dict[str, Any]],
    scoped_farm_ids: set[Any],
    target_year: int | None,
    target_month: int | None,
    extra_filters: dict[str, Any],
    records: Any,
) -> list[dict[str, Any]]:
    monthly_by_farm = defaultdict(lambda: [Decimal(0), Decimal(0)])
    for item in records(MONTHLY):
        fid = item.get("farm_id")
        if fid not in scoped_farm_ids:
            continue
        d = _day(item.get("month_start"))
        if target_month is not None and d.month != target_month:
            continue
        if target_year is not None and d.year != target_year:
            continue
        monthly_by_farm[fid][0] += _number(
            (item.get("energy_metrics") or {}).get("monthly_total_kwh")
        )
        monthly_by_farm[fid][1] += _number(
            (item.get("water_metrics") or {}).get("monthly_total_m3")
        )

    lots_by_farm = defaultdict(list)
    for lot in records(ROWS, "fact_lot"):
        fid = lot.get("farm_id")
        if fid not in scoped_farm_ids:
            continue
        d = _day(lot.get("delivery_date") or lot.get("date") or datetime.now(UTC))
        if target_month is not None and d.month != target_month:
            continue
        if target_year is not None and d.year != target_year:
            continue
        lots_by_farm[fid].append(lot)

    items = []
    for f in scoped_farms:
        fid = f.get("farm_id")
        if fid is None:
            continue
        farm_name = f.get("farm_name") or f"Granja {fid}"
        manager_name = (
            f.get("manager_name") or f.get("manager") or f.get("regional_management")
        )
        state = f.get("state") or f.get("uf") or ""
        city = f.get("city") or ""
        regional_management = f.get("regional_management") or ""
        location = f"{city} - {state}".strip(" -") if (city or state) else "Brasil"

        kwh, m3 = monthly_by_farm[fid]
        total_consumption = f"{_rounded(kwh, 1)} kWh | {_rounded(m3, 1)} m³"

        farm_lots = lots_by_farm[fid]
        lots_count = len(farm_lots)
        total_cost = sum((_number(l.get("cost")) for l in farm_lots), Decimal(0))
        total_chickens = sum(
            (
                _number(l.get("received_chickens") or l.get("chickens"))
                for l in farm_lots
            ),
            Decimal(0),
        )

        avg_lot_cost = (
            _rounded(total_cost / Decimal(lots_count), 2) if lots_count > 0 else 0.0
        )
        avg_cost_per_bird = (
            _rounded(total_cost / total_chickens, 2)
            if total_chickens > Decimal(0)
            else 0.0
        )

        items.append(
            {
                "farm_id": fid,
                "farm_name": farm_name,
                "manager_name": manager_name,
                "location": location,
                "state": state,
                "regional_management": regional_management,
                "total_consumption": total_consumption,
                "lots_count": lots_count,
                "avg_lot_cost": avg_lot_cost,
                "avg_cost_per_bird": avg_cost_per_bird,
            }
        )

    search = extra_filters.get("search")
    if search:
        q = search.casefold().strip()
        items = [
            it
            for it in items
            if q in it["farm_name"].casefold()
            or (it["manager_name"] and q in it["manager_name"].casefold())
            or q in it["location"].casefold()
            or q in str(it["farm_id"])
        ]

    sort_by = extra_filters.get("sort_by") or "farm_name"
    order = (extra_filters.get("order") or "asc").lower()
    reverse = order == "desc"

    def sort_key(it):
        val = it.get(sort_by)
        if val is None:
            return "" if isinstance(sort_by, str) else 0
        return val

    items.sort(key=sort_key, reverse=reverse)

    total = len(items)
    page = max(1, int(extra_filters.get("page") or 1))
    limit = max(1, int(extra_filters.get("limit") or 10))
    offset = (page - 1) * limit
    paged_items = items[offset : offset + limit]

    return [
        {
            "total": total,
            "page": page,
            "limit": limit,
            "items": paged_items,
        }
    ]


class AnalyticsRepository:
    """MongoDB reader using a pooled, TLS-verified PyMongo client.

    Blocking reads execute in a worker thread, not on FastAPI's event loop.
    The MongoClient is safe to share between concurrent threads.
    """

    def __init__(
        self,
        database_url: str,
        *,
        database_name: str = "ouros_analytics_poc",
        connect_timeout_seconds: float = 5.0,
        retry_backoff_seconds: float = 5.0,
    ) -> None:
        validate_mongodb_uri(database_url, database_name)
        self.database_name = database_name
        self.retry_backoff_seconds = retry_backoff_seconds
        self._retry_after = 0.0
        self._client = MongoClient(
            database_url,
            tls=True,
            tlsAllowInvalidCertificates=False,
            tlsAllowInvalidHostnames=False,
            serverSelectionTimeoutMS=int(connect_timeout_seconds * 1000),
            connectTimeoutMS=int(connect_timeout_seconds * 1000),
            socketTimeoutMS=int(max(connect_timeout_seconds * 3, 15) * 1000),
            retryWrites=False,
        )
        self._database = self._client[database_name]

    async def ping(self) -> None:
        try:
            await asyncio.to_thread(self._client.admin.command, "ping")
            self._retry_after = 0.0
        except (PyMongoError, OSError, TimeoutError) as exc:
            self._retry_after = time.monotonic() + self.retry_backoff_seconds
            raise AnalyticsUnavailable("MongoDB Atlas is unavailable") from exc

    async def close(self) -> None:
        await asyncio.to_thread(self._client.close)

    def _state(self) -> dict[str, Any] | None:
        return self._database[STATE].find_one({"_id": SYNC_ID})

    def _docs(self, collection: str, filter_by: dict[str, Any]):
        """Stream server-filtered records without accumulating raw datasets."""
        return self._database[collection].find(filter_by)

    def _fetch_corporate(
        self,
        operation: str,
        records: Any,
        extra_filters: dict[str, Any],
        cutoff: Any,
    ) -> list[dict[str, Any]]:
        all_farms = list(records(ROWS, "dim_farm"))

        raw_state = extra_filters.get("state")
        filter_state: str | None = None
        if raw_state and str(raw_state).strip().lower() not in (
            "todos",
            "todas",
            "all",
            "",
        ):
            filter_state = str(raw_state).strip().upper()

        raw_mgmt = extra_filters.get("management")
        filter_mgmt: str | None = None
        if raw_mgmt and str(raw_mgmt).strip().lower() not in (
            "todos",
            "todas",
            "all",
            "",
        ):
            filter_mgmt = str(raw_mgmt).strip()

        target_year, target_month = _parse_month_filter(extra_filters.get("month"))

        scoped_farms = all_farms
        if filter_state:
            scoped_farms = [
                f
                for f in scoped_farms
                if str(f.get("state") or f.get("uf") or "").strip().upper()
                == filter_state
            ]
        if filter_mgmt:
            scoped_farms = [
                f
                for f in scoped_farms
                if str(
                    f.get("regional_management")
                    or f.get("management")
                    or f.get("manager_name")
                    or ""
                )
                .strip()
                .casefold()
                == filter_mgmt.casefold()
            ]
        scoped_farm_ids = {
            f["farm_id"] for f in scoped_farms if f.get("farm_id") is not None
        }

        if operation == "corporate_filters":
            return _corporate_filters(all_farms, records)
        if operation == "corporate_kpis":
            return _corporate_kpis(
                scoped_farm_ids, extra_filters, records, filter_state, filter_mgmt
            )
        if operation == "corporate_farms_table":
            return _corporate_farms_table(
                scoped_farms,
                scoped_farm_ids,
                target_year,
                target_month,
                extra_filters,
                records,
            )
        return _exec_corporate_charts(
            operation,
            scoped_farm_ids,
            all_farms,
            target_year,
            target_month,
            cutoff,
            records,
        )

    def _fetch_admin_ai(
        self,
        operation: str,
        records: Any,
    ) -> list[dict[str, Any]]:
        raw_sessions = list(records(ROWS, "fact_ai_session"))
        if not raw_sessions:
            return []
        if operation == "admin_ai_kpis":
            total_cost = sum(
                (_number(s.get("cost_brl")) for s in raw_sessions), Decimal(0)
            )
            total_tokens = sum(
                (_number(s.get("total_tokens")) for s in raw_sessions), Decimal(0)
            )
            active_users = len(
                {s.get("user_id") for s in raw_sessions if s.get("user_id") is not None}
            )
            unit_cost = (
                _rounded((total_cost * Decimal(1000)) / total_tokens, 2)
                if total_tokens > 0
                else 0.0
            )
            return [
                {
                    "total_cost_brl": _rounded(total_cost, 2),
                    "unit_cost_brl": unit_cost,
                    "active_users": active_users,
                    "total_tokens": int(total_tokens),
                }
            ]
        normalized: list[dict[str, Any]] = []
        for s in raw_sessions:
            item = dict(s)
            if "cost_brl" in item:
                item["cost_brl"] = _rounded(_number(item["cost_brl"]), 2)
            if "accuracy_rate" in item:
                item["accuracy_rate"] = _rounded(_number(item["accuracy_rate"]), 2)
            normalized.append(item)
        return normalized

    def _fetch_sync(
        self, operation: str, args: tuple[Any, ...]
    ) -> list[dict[str, Any]]:
        state = self._state()
        if operation == "sync_status":
            if not state:
                return [{"last_updated_at": None, "has_error": False}]
            return [
                {
                    "last_updated_at": state.get("last_success_at")
                    or state.get("last_sync"),
                    "has_error": state.get("status") != "success",
                }
            ]

        if not state or state.get("status") != "success" or not state.get("run_id"):
            raise AnalyticsUnavailable("Atlas analytics snapshot is not complete")

        run_id = state["run_id"]
        extra_filters: dict[str, Any] = {}
        period_days: int | None = None
        if operation in CORPORATE_OPERATIONS:
            if len(args) < 2:
                raise AnalyticsQueryError("Signed analytics scope is missing")
            farm_id, enterprise_id = args[:2]
            is_global_admin = False
            for extra_arg in args[2:]:
                if isinstance(extra_arg, dict):
                    if extra_arg.get("_global_admin"):
                        is_global_admin = True
                    extra_filters.update(
                        {k: v for k, v in extra_arg.items() if k != "_global_admin"}
                    )
                elif isinstance(extra_arg, int):
                    period_days = extra_arg
            if farm_id is not None or (enterprise_id is None and not is_global_admin):
                raise AnalyticsQueryError(
                    "Corporate operations require enterprise scope"
                )
            if enterprise_id is not None:
                if (
                    isinstance(enterprise_id, bool)
                    or not isinstance(enterprise_id, int)
                    or enterprise_id < 1
                ):
                    raise AnalyticsQueryError("Invalid analytics scope")
                scope = {"enterprise_id": enterprise_id}
            else:
                scope = {}
        elif operation in ADMIN_AI_OPERATIONS:
            scope, period_days = {}, None
            for extra_arg in args:
                if isinstance(extra_arg, dict):
                    extra_filters.update(extra_arg)
                elif (
                    isinstance(extra_arg, int)
                    and not isinstance(extra_arg, bool)
                    and extra_arg > 0
                ):
                    scope["enterprise_id"] = extra_arg
        elif operation in USER_OPERATIONS:
            if len(args) < 2:
                raise AnalyticsQueryError("Signed analytics scope is missing")
            farm_id, enterprise_id = args[:2]
            if (farm_id is None) == (enterprise_id is None):
                raise AnalyticsQueryError("Expected exactly one signed analytics scope")
            if isinstance(farm_id if farm_id is not None else enterprise_id, bool):
                raise AnalyticsQueryError("Invalid analytics scope")
            identifier = farm_id if farm_id is not None else enterprise_id
            if not isinstance(identifier, int) or identifier < 1:
                raise AnalyticsQueryError("Invalid analytics scope")
            scope = (
                {"farm_id": farm_id}
                if farm_id is not None
                else {"enterprise_id": enterprise_id}
            )
            period_days = args[2] if len(args) > 2 else None
        elif operation in ADMIN_OPERATIONS:
            if args:
                raise AnalyticsQueryError("Admin analytics queries do not accept scope")
            scope, period_days = {}, None
        else:
            raise AnalyticsQueryError("Unknown MongoDB analytics operation")

        cutoff = _date_filter(
            period_days if operation in DATED_OPERATIONS else None,
            monthly=operation in MONTHLY_OPERATIONS,
        )

        def records(collection: str, dataset: str | None = None, **extra):
            criteria = {"_sync_run": run_id, **scope, **extra}
            if dataset is not None:
                criteria["dataset"] = dataset
            return self._docs(collection, criteria)

        if operation in CORPORATE_OPERATIONS:
            return self._fetch_corporate(operation, records, extra_filters, cutoff)

        if operation in ADMIN_AI_OPERATIONS:
            return self._fetch_admin_ai(operation, records)

        if operation in {
            "current_flock",
            "capacity_utilization",
            "farm_capacity",
            "farm-count",
            "current-flock",
            "capacity-utilization",
        }:
            farms = list(records(ROWS, "dim_farm"))
            if operation == "farm-count":
                return [{"value": len(farms)}]
            chickens = sum((_number(f.get("chickens_now")) for f in farms), Decimal(0))
            if operation in {"current_flock", "current-flock"}:
                return [{"value": int(chickens)}]
            capacity = sum(
                (_number(f.get("poultry_capacity")) for f in farms), Decimal(0)
            )
            if operation in {"capacity_utilization", "capacity-utilization"}:
                return [
                    {"value": _rounded(chickens * 100 / capacity) if capacity else 0.0}
                ]
            return [
                {
                    "farm_name": f.get("farm_name"),
                    "chickens_now": f.get("chickens_now"),
                    "poultry_capacity": f.get("poultry_capacity"),
                }
                for f in sorted(
                    farms,
                    key=lambda x: (x.get("farm_name") or "", x.get("farm_id") or 0),
                )
            ]

        if operation in {
            "mortality_rate",
            "lot_throughput",
            "lot_mortality",
            "lot_cost",
        }:
            daily = defaultdict(
                lambda: [Decimal(0), Decimal(0), Decimal(0), Decimal(0)]
            )
            for lot in records(ROWS, "fact_lot"):
                day = _day(lot["delivery_date"])
                if cutoff and day < cutoff:
                    continue
                totals = daily[day]
                for index, field in enumerate(
                    ("received_chickens", "delivered_chickens", "lost_chickens", "cost")
                ):
                    totals[index] += _number(lot.get(field))
            if operation == "mortality_rate":
                received = sum((v[0] for v in daily.values()), Decimal(0))
                lost = sum((v[2] for v in daily.values()), Decimal(0))
                return [{"value": _rounded(lost * 100 / received) if received else 0.0}]
            result = []
            for day, (received, delivered, lost, cost) in sorted(daily.items()):
                if operation == "lot_throughput":
                    result.append(
                        {
                            "delivery_date": day.isoformat(),
                            "received_chickens": int(received),
                            "delivered_chickens": int(delivered),
                            "lost_chickens": int(lost),
                        }
                    )
                elif operation == "lot_mortality":
                    result.append(
                        {
                            "delivery_date": day.isoformat(),
                            "mortality_rate_pct": _rounded(lost * 100 / received)
                            if received
                            else 0.0,
                        }
                    )
                else:
                    result.append(
                        {"delivery_date": day.isoformat(), "cost": _rounded(cost)}
                    )
            return result

        if operation in {
            "monthly_consumption",
            "resource_efficiency",
            "monthly-water-consumption",
            "relative_consumption",
        }:
            monthly = defaultdict(lambda: [Decimal(0), Decimal(0), Decimal(0)])
            for item in records(MONTHLY):
                month = _day(item["month_start"])
                if cutoff and month < cutoff:
                    continue
                totals = monthly[month]
                totals[0] += _number(
                    (item.get("water_metrics") or {}).get("monthly_total_m3")
                )
                totals[1] += _number(
                    (item.get("energy_metrics") or {}).get("monthly_total_kwh")
                )
                totals[2] += _number(item.get("chickens_reference"))
            result = []
            if operation == "relative_consumption":
                max_combined = max(
                    (w + e for w, e, _ in monthly.values()),
                    default=Decimal(0),
                )
                for month, (water, energy, _) in sorted(monthly.items()):
                    key = month.isoformat()
                    combined = water + energy
                    pct = (
                        _rounded((combined * Decimal(100) / max_combined), 1)
                        if max_combined > 0
                        else 0.0
                    )
                    result.append(
                        {
                            "month_start": key,
                            "relative_consumption_pct": min(100.0, max(0.0, pct)),
                        }
                    )
                return result
            for month, (water, energy, chickens) in sorted(monthly.items()):
                key = month.isoformat()
                if operation == "monthly-water-consumption":
                    result.append(
                        {"month_start": key, "water_consumed_m3": _rounded(water, 3)}
                    )
                elif operation == "monthly_consumption":
                    result.append(
                        {
                            "month_start": key,
                            "water_consumed_m3": _rounded(water, 3),
                            "energy_consumed_kwh": _rounded(energy, 3),
                        }
                    )
                else:
                    result.append(
                        {
                            "month_start": key,
                            "water_m3_per_chicken": _rounded(water / chickens, 4)
                            if chickens
                            else None,
                            "energy_kwh_per_chicken": _rounded(energy / chickens, 4)
                            if chickens
                            else None,
                        }
                    )
            return result

        if operation == "water_consumption_by_reading":
            daily = defaultdict(lambda: Decimal(0))
            for bucket in records(BUCKETS, metric="water"):
                for reading in bucket.get("readings", []):
                    day = _day(reading["date"])
                    if not cutoff or day >= cutoff:
                        daily[day] += _number(reading.get("value"))
            return [
                {
                    "registration_date": day.isoformat(),
                    "water_consumed_m3": _rounded(value, 3),
                }
                for day, value in sorted(daily.items())
            ]

        if operation in {"goal_status", "goal_type"}:
            if "enterprise_id" in scope:
                farm_ids = [
                    f["farm_id"]
                    for f in records(ROWS, "dim_farm")
                    if f.get("farm_id") is not None
                ]
                goal_filter = {
                    "_sync_run": run_id,
                    "dataset": "fact_goal",
                    "farm_id": {"$in": farm_ids},
                }
            else:
                goal_filter = {"_sync_run": run_id, "dataset": "fact_goal", **scope}
            field = "goal_status" if operation == "goal_status" else "goal_type"
            counts = defaultdict(int)
            for goal in self._docs(ROWS, goal_filter):
                if goal.get(field) is not None:
                    counts[str(goal[field])] += 1
            return [
                {"label": label, "value": count}
                for label, count in sorted(counts.items(), key=lambda x: (-x[1], x[0]))
            ]

        raise AnalyticsQueryError("Unsupported analytics operation")

    async def fetch(
        self,
        operation: str,
        query: str,
        *args: Any,
    ) -> list[dict[str, Any]]:
        """Execute an allowlisted analytics operation; never run caller SQL."""
        started = time.monotonic()
        try:
            if time.monotonic() < self._retry_after:
                raise AnalyticsUnavailable("MongoDB Atlas is in retry backoff")
            rows = await asyncio.to_thread(self._fetch_sync, operation, args)
            ANALYTICS_QUERIES.labels(operation, "success").inc()
            return rows
        except AnalyticsQueryError:
            ANALYTICS_QUERIES.labels(operation, "error").inc()
            ANALYTICS_ERRORS.labels(operation, "invalid_operation").inc()
            raise
        except AnalyticsUnavailable:
            ANALYTICS_QUERIES.labels(operation, "error").inc()
            ANALYTICS_ERRORS.labels(operation, "unavailable").inc()
            raise
        except (PyMongoError, OSError, TimeoutError) as exc:
            self._retry_after = time.monotonic() + self.retry_backoff_seconds
            ANALYTICS_QUERIES.labels(operation, "error").inc()
            ANALYTICS_ERRORS.labels(operation, type(exc).__name__).inc()
            raise AnalyticsUnavailable("MongoDB Atlas query unavailable") from exc
        except (
            ValueError,
            TypeError,
            KeyError,
            AttributeError,
            ArithmeticError,
        ) as exc:
            ANALYTICS_QUERIES.labels(operation, "error").inc()
            ANALYTICS_ERRORS.labels(operation, type(exc).__name__).inc()
            raise AnalyticsQueryError("Invalid Atlas analytics document") from exc
        finally:
            ANALYTICS_DURATION.labels(operation).observe(time.monotonic() - started)
