def validate_mongodb_uri(uri: str, database: str) -> None:
    """Reject TLS bypass and wrong destination before creating a client."""
    if not uri.startswith(("mongodb://", "mongodb+srv://")):
        raise ValueError("Analytics MongoDB URI must use mongodb:// or mongodb+srv://")
    for key, value in parse_qsl(urlsplit(uri).query, keep_blank_values=True):
        option, setting = key.casefold(), value.casefold()
        if option in BLOCKED_TLS_OPTIONS and setting != "false":
            raise ValueError("Analytics MongoDB URI enables insecure TLS")
        if option in {"ssl", "tls"} and setting != "true":
            raise ValueError("Analytics MongoDB URI must not disable TLS")
    if not database.startswith("ouros_analytics_poc"):
        raise ValueError(
            "Analytics MongoDB database must use ouros_analytics_poc prefix"
        )


def _number(value: Any) -> Decimal:
    if value is None:
        return Decimal(0)
    if isinstance(value, Decimal128):
        return value.to_decimal()
    return Decimal(str(value))


def _rounded(value: Decimal, places: int = 2) -> float:
    return float(round(value, places))


def _day(value: Any) -> date:
    if isinstance(value, datetime):
        return value.date()
    if isinstance(value, date):
        return value
    return date.fromisoformat(str(value)[:10])


def _date_filter(days: int | None, *, monthly: bool = False) -> date | None:
    if days is None:
        return None
    if not 1 <= days <= 732:
        raise AnalyticsQueryError("Invalid chart period")

    today = datetime.now(UTC).date()
    if monthly:
        previous_year_start = date(today.year - 1, 1, 1)
        cutoff = today - timedelta(days=days - 1)
        return min(previous_year_start, cutoff.replace(day=1))
    return today - timedelta(days=days - 1)


def _format_currency_brl(val: float) -> str:
    s = f"{val:,.2f}".replace(",", "X").replace(".", ",").replace("X", ".")
    return f"R$ {s}"


def _parse_month_filter(val: Any) -> tuple[int | None, int | None]:
    if not val:
        return None, None
    s = str(val).strip()
    if s.lower() in ("atual", "todos", "todas", "all", ""):
        return None, None
    if s.lower().startswith("ano ") and s[4:].strip().isdigit():
        return int(s[4:].strip()), None
    if "-" in s:
        parts = s.split("-")
        try:
            return int(parts[0]), int(parts[1])
        except (ValueError, IndexError):
            return None, None
    if "/" in s:
        parts = s.split("/")
        try:
            return int(parts[1]), int(parts[0])
        except (ValueError, IndexError):
            return None, None
    if s.isdigit():
        try:
            m = int(s)
            if 1 <= m <= 12:
                return None, m
        except ValueError:
            pass
    return None, None


def _resolve_region(
    farm: dict[str, Any] | None = None, lot: dict[str, Any] | None = None
) -> str:
    farm = farm or {}
    lot = lot or {}

    raw_region = farm.get("region") or lot.get("region")
    if raw_region:
        normalized = REGION_NORMALIZE.get(str(raw_region).casefold().strip())
        if normalized:
            return normalized

    st = (
        str(
            farm.get("state")
            or farm.get("uf")
            or lot.get("state")
            or lot.get("uf")
            or ""
        )
        .upper()
        .strip()
    )
    if st in STATE_TO_REGION:
        return STATE_TO_REGION[st]

    mgmt = (
        str(farm.get("regional_management") or farm.get("management") or "")
        .casefold()
        .strip()
    )
    for key, canonical in REGION_NORMALIZE.items():
        if key in mgmt:
            return canonical

    return "Centro-Oeste"


def _calc_box_stats(values: list[Decimal]) -> dict[str, Any]:
    """Calculates min, q1, median, q3, max, avg, total_cost, lots_count for Box Plot."""
    if not values:
        return {
            "min": 0.0,
            "q1": 0.0,
            "median": 0.0,
            "q3": 0.0,
            "max": 0.0,
            "avg": 0.0,
            "total_cost": 0.0,
            "lots_count": 0,
        }
    float_vals = sorted([float(v) for v in values])
    n = len(float_vals)
    total = sum(float_vals)
    if n == 1:
        v = round(float_vals[0], 2)
        return {
            "min": v,
            "q1": v,
            "median": v,
            "q3": v,
            "max": v,
            "avg": v,
            "total_cost": v,
            "lots_count": 1,
        }
    med = statistics.median(float_vals)
    if n >= 4:
        quants = statistics.quantiles(float_vals, n=4)
        q1 = quants[0]
        q3 = quants[2]
    elif n == 2:
        q1 = float_vals[0]
        q3 = float_vals[1]
    else:  # n == 3
        q1 = (float_vals[0] + float_vals[1]) / 2.0
        q3 = (float_vals[1] + float_vals[2]) / 2.0

    return {
        "min": round(float_vals[0], 2),
        "q1": round(q1, 2),
        "median": round(med, 2),
        "q3": round(q3, 2),
        "max": round(float_vals[-1], 2),
        "avg": round(total / n, 2),
        "total_cost": round(total, 2),
        "lots_count": n,
    }


